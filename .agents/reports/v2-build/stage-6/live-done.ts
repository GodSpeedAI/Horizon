import { chromium } from "/home/sprime01/projects/Horizon/node_modules/playwright-core/index.mjs";
import { readdirSync } from "node:fs";
const out = process.argv[2]!;
const root = `${process.env.HOME}/.cache/ms-playwright`;
const exe = `${root}/${readdirSync(root).find((d) => d.startsWith("chromium-"))}/chrome-linux64/chrome`;
const browser = await chromium.launch({ executablePath: exe, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors: string[] = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto("http://127.0.0.1:4339/desk", { waitUntil: "networkidle" });
await page.waitForTimeout(2000);
await page.getByRole("link", { name: /^Decide/ }).or(page.getByRole("button", { name: /^Decide/ })).first().click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}-1-decide.png`, fullPage: true });
const lines = (await page.innerText("main").catch(() => page.innerText("body"))).split("\n");
console.log("DECIDE:\n" + lines.slice(0, 30).join("\n"));
const done = page.getByRole("button", { name: /^Mark done/ }).nth(Number(process.argv[3] ?? 0));
console.log("mark-done buttons:", await page.getByRole("button", { name: /^Mark done/ }).count());
await done.click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-2-after-click.png`, fullPage: true });
console.log("AFTER CLICK:\n" + (await page.innerText("body")).split("\n").filter((l) => /done|why|reason|confirm|justif|waiting|refus/i.test(l)).slice(0, 15).join("\n"));
const reason = page.getByLabel(/Your reason/).first();
await reason.fill("Release notes read and checked against the release list.");
await page.screenshot({ path: `${out}-3-reason.png`, fullPage: true });
await page.getByRole("button", { name: /^Confirm: Mark done/ }).first().click();
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}-4-done.png`, fullPage: true });
console.log("AFTER CONFIRM:\n" + (await page.innerText("body")).split("\n").filter((l) => /done|recorded|waiting|refus|out of date|of \d/i.test(l)).slice(0, 12).join("\n"));
console.log("ERRORS:", JSON.stringify(errors));
await browser.close();
